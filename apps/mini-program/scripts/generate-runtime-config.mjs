import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

import {
  assertReleaseApiBaseUrl,
  isPlaceholderApiBaseUrl,
} from "../../../scripts/production-gates.mjs";

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputArgument = process.argv.find((argument) => argument.startsWith("--output="));
const outputPath = outputArgument
  ? path.resolve(packageRoot, outputArgument.slice("--output=".length))
  : path.join(packageRoot, "src", "config", "runtime.generated.ts");
const localMode = process.argv.includes("--local");
const trialMode = process.argv.includes("--trial");
const productionMode = process.argv.includes("--production");

if ([localMode, trialMode, productionMode].filter(Boolean).length > 1) {
  throw new Error("--local, --trial and --production are mutually exclusive");
}

function readBoolean(name, fallback) {
  const value = process.env[name];
  if (value === undefined || value === "") {
    return fallback;
  }
  if (value === "true") {
    return true;
  }
  if (value === "false") {
    return false;
  }
  throw new Error(`${name} must be either true or false`);
}

function normalizeBaseUrl(value) {
  return value.endsWith("/") ? value.slice(0, -1) : value;
}

function isHttpsUrl(value) {
  return /^https:\/\/[A-Za-z0-9.-]+(?::\d{1,5})?(?:\/[^\s?#]*)?$/.test(value);
}

function isLoopbackHttpUrl(value) {
  return /^http:\/\/(?:localhost|127\.0\.0\.1|\[::1\])(?::\d{1,5})?(?:\/[^\s?#]*)?$/.test(value);
}

function readBuildMode() {
  if (productionMode) {
    return "production";
  }
  if (trialMode) {
    return "development";
  }
  const value =
    process.env.MINIPROGRAM_BUILD_MODE ??
    (process.env.NODE_ENV === "production" ? "production" : "development");
  if (value !== "development" && value !== "production") {
    throw new Error("MINIPROGRAM_BUILD_MODE must be development or production");
  }
  return value;
}

function readShortString(name, fallback, maximumLength) {
  const value = process.env[name] ?? fallback;
  if (value.length > maximumLength || /[\r\n]/.test(value)) {
    throw new Error(`${name} is invalid or too long`);
  }
  return value;
}

const buildMode = readBuildMode();
if (localMode && buildMode === "production") {
  throw new Error("--local cannot be used for a production build");
}

const apiBaseUrl = normalizeBaseUrl(
  readShortString("MINIPROGRAM_API_BASE_URL", localMode ? "http://127.0.0.1:3100" : "", 512),
);
const allowInsecureLocalhost = localMode
  ? true
  : readBoolean("MINIPROGRAM_ALLOW_INSECURE_LOCALHOST", false);
const allowPlaceholderApi = readBoolean("MINIPROGRAM_ALLOW_PLACEHOLDER_API", false);

if (buildMode === "production") {
  assertReleaseApiBaseUrl(apiBaseUrl);
  if (allowInsecureLocalhost) {
    throw new Error("Production builds cannot allow insecure localhost requests");
  }
} else if (
  apiBaseUrl !== "" &&
  !isHttpsUrl(apiBaseUrl) &&
  !(allowInsecureLocalhost && isLoopbackHttpUrl(apiBaseUrl))
) {
  throw new Error(
    "MINIPROGRAM_API_BASE_URL must use HTTPS, or loopback HTTP with MINIPROGRAM_ALLOW_INSECURE_LOCALHOST=true",
  );
}
if (trialMode && !isHttpsUrl(apiBaseUrl)) {
  throw new Error("Trial MINIPROGRAM_API_BASE_URL must be a non-empty HTTPS URL");
}
if (trialMode && isPlaceholderApiBaseUrl(apiBaseUrl) && !allowPlaceholderApi) {
  throw new Error(
    "Trial placeholder API requires MINIPROGRAM_ALLOW_PLACEHOLDER_API=true to mark it as internal-only",
  );
}

const brandName = readShortString("MINIPROGRAM_BRAND_NAME", "轻连 WiFi", 40).trim();
if (brandName.length === 0) {
  throw new Error("MINIPROGRAM_BRAND_NAME cannot be empty");
}

// Only this allowlisted, non-secret object is serialized. In particular,
// Server-only credentials and other process environment values are never read or emitted.
const config = {
  enableAds: readBoolean("ENABLE_ADS", false),
  enableAnalytics: readBoolean("ENABLE_ANALYTICS", true),
  enableWifiDiagnostics: buildMode !== "production" && readBoolean("ENABLE_WIFI_DIAGNOSTICS", true),
  apiBaseUrl,
  requestTimeoutMs: 8_000,
  connectTimeoutMs: 20_000,
  legacyWifiAdapterEnabled: readBoolean("MINIPROGRAM_ENABLE_LEGACY_WIFI_API", false),
  legacyWifiManualSystemConnection: readBoolean(
    "MINIPROGRAM_LEGACY_WIFI_MANUAL_SYSTEM_CONNECTION",
    false,
  ),
  allowInsecureLocalhost,
  adUnitId: readShortString("MINIPROGRAM_AD_UNIT_ID", "", 128).trim(),
  brandName,
};

const source = `// Generated by scripts/generate-runtime-config.mjs. Do not edit manually.
// This file contains public mini-program settings only; never add secrets.
export const GENERATED_MINI_PROGRAM_RUNTIME_CONFIG = {
  enableAds: ${config.enableAds},
  enableAnalytics: ${config.enableAnalytics},
  enableWifiDiagnostics: ${config.enableWifiDiagnostics},
  apiBaseUrl: ${JSON.stringify(config.apiBaseUrl)},
  requestTimeoutMs: ${config.requestTimeoutMs},
  connectTimeoutMs: ${config.connectTimeoutMs},
  legacyWifiAdapterEnabled: ${config.legacyWifiAdapterEnabled},
  legacyWifiManualSystemConnection: ${config.legacyWifiManualSystemConnection},
  allowInsecureLocalhost: ${config.allowInsecureLocalhost},
  adUnitId: ${JSON.stringify(config.adUnitId)},
  brandName: ${JSON.stringify(config.brandName)},
} as const;
`;

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, source, "utf8");

process.stdout.write(
  `Generated ${path.relative(packageRoot, outputPath)} for ${
    trialMode ? "trial" : buildMode
  } mode (${apiBaseUrl || "no API URL"})\n`,
);
